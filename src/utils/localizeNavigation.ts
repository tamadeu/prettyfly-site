export function localizeNavigationText(text: string): string {
  const demoList = /^Demo list (\d+)$/.exec(text);
  if (demoList) return `Demonstração ${demoList[1]}`;

  const discount = /^(?:UP TO |SALE UP TO )(\d+)% OFF$/.exec(text);
  if (discount) return `ATÉ ${discount[1]}% DE DESCONTO`;

  return navigationTranslations[text] ?? text;
}
